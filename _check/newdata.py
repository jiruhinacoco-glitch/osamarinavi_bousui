def mkitem(i, t):
    name, ad, moto, ko, mk, sz, m2, tan, st = t[0], t[1], t[2]+'（株）', t[3], t[4], t[5], t[6], t[7], t[8]
    d = {'id': 'J%03d' % (78+i), 'n': name, 'st': st, 'ad': ad, 'e': moto,
         'ko': ko, 'mk': mk, 'sz': sz, 'm': m2, 'tan': tan, 'un': '㎡',
         'amt': m2*tan, 'kb': None, 'cb': None, 'fb': None, 'fy': None,
         'sb': None, 'nb': None,
         'sh': '翌月末振込' if i % 3 else '翌々月末振込',
         'p': 0, 'nin': 0, 'y': [0,0,0,0], 'a': None, 'tb': None}
    amt = d['amt']
    # 予算の内訳（材料31%・労務29%・外注6%・経費14%＝計80%。端数は決め打ちの揺らぎ）
    j = (i*7) % 5 - 2   # -2..2%
    y = [round(amt*0.31), round(amt*(0.29+j/100.0)), round(amt*0.06), round(amt*0.14)]
    if st == 'hikiai':
        d.update(tan=0, amt=0, fy='現地調査 日程調整中')
        return d
    d['y'] = y
    if st == 'kan':
        kb, cb, fb = t[9]
        nin = max(4, round(y[1]/25000))
        a = [round(v*(1 + ((i*13+k*7) % 7 - 3)/100.0)) for k, v in enumerate(y)]
        # 完成月の翌月半ばに請求、翌月末に入金
        sb = fb[:8]+'28' if fb[8:] < '15' else (fb[:5] + ('%02d' % (int(fb[5:7]) % 12 + 1)) + '-15')
        d.update(kb=kb, cb=cb, fb=fb, sb=fb, nb=sb, p=100, nin=nin, a=a)
    elif st == 'kou':
        kb, cb, fb = t[9]; p = t[10]
        nin = max(4, round(y[1]/25000))
        a = [round(v*p/100.0) for v in y]
        d.update(kb=kb, cb=cb, fb=fb, fy=fb, sb=fb, p=p, nin=nin, a=a)
    elif st == 'keiyaku':
        kb, cb = t[9]
        d.update(kb=kb, cb=cb, fy=cb+' 着工予定')
    elif st == 'mit':
        cb = t[9]
        d.update(cb=cb, fy=cb[:7]+' 着工予定')
    return d

